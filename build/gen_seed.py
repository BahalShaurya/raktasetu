    seq = 0
    for did in chosen:
        reg_seq[0] += 1
        rid = reg_seq[0]
        slot = dt.time(R.choice([9, 9, 10, 10, 11, 12, 13, 14]), R.choice([0, 15, 30, 45]))
        rat = dt.datetime.combine(day - dt.timedelta(days=R.randint(1, 12)), dt.time(R.randint(9, 21), R.randint(0, 59)))
        if rat.date() < by_id[did]["reg_on"]: rat = dt.datetime.combine(by_id[did]["reg_on"], dt.time(18, 0))
        by = R.choice(volunteers + [None, None, None])
        roll = R.random()
        if roll < .07: status = "CANCELLED"
        elif roll < .14: status = "NO_SHOW"
        else:
            bad = R.choice(["LOW_HB", "UNDERWEIGHT", "FEVER", "BP", "TATTOO", "ANTIBIOTIC", "VACCINE", "PULSE"]) if R.random() < .15 else None
            if by_id[did]["g"] == "F" and bad is None and R.random() < .12: bad = "LOW_HB"
            status = "DEFERRED" if bad else "DONATED"
        regs.append((eid, did, slot, rat, status, by, rid))
        if status in ("DONATED", "DEFERRED"):
            seq += 1
            v = vitals(by_id[did]["g"], bad if status == "DEFERRED" else None)
            sat = dt.datetime.combine(day, dt.time(9, 20)) + dt.timedelta(minutes=seq * 11)
            screens.append((rid, R.choice(coords), sat, v))
            if status == "DEFERRED":
                def_until[did] = max(def_until.get(did, day), day + dt.timedelta(days=RDAYS[v["reason"]]))
            else:
                bag_seq[eid] = bag_seq.get(eid, 0) + 1
                vol_ml = 450 if v["wt"] > 55 else 350
                cat = sat + dt.timedelta(minutes=18)
                dons.append(dict(rid=rid, bag=f"RS{day.strftime('%y%m')}-{bag_seq[eid]:03d}", vol=vol_ml, cat=cat,
                                 by=R.choice(coords), eid=eid, did=did))
