by_id = {d["id"]: d for d in donors}
last_don = {}          # donor -> last donation date
def_until = {}         # donor -> temporary deferral end
perm = set()
def gap(d): return 120 if by_id[d]["g"] == "F" else 90
def next_elig(did):
    c = []
    if did in last_don: c.append(last_don[did] + dt.timedelta(days=gap(did)))
    if did in def_until: c.append(def_until[did])
    return max(c) if c else None
def eligible(did, on):
    if did in perm: return False
    d = by_id[did]
    age = (on - d["dob"]).days / 365.25
    if age < 18 or age > 65: return False
    ne = next_elig(did)
    return ne is None or ne <= on

